import { useEffect, useRef, useState } from 'react';
import { AnimatePresence } from 'framer-motion';
import AnimatedBackground from '../components/chat/AnimatedBackground';
import ChatHeader from '../components/chat/ChatHeader';
import WelcomeScreen from '../components/chat/WelcomeScreen';
import MessageBubble from '../components/chat/MessageBubble';
import TypingIndicator from '../components/chat/TypingIndicator';
import ChatInput from '../components/chat/ChatInput';
import { sendChatQuery } from '../lib/api';

// after this long without a reply, assume the free-tier backend is cold-starting
const SLOW_REPLY_MS = 6000;

let nextId = 0;
const makeId = () => ++nextId;

const ChatPage = ({ user, onLogout }) => {
  const [messages, setMessages] = useState([]);
  const [input, setInput] = useState('');
  const [isThinking, setIsThinking] = useState(false);
  const [isSlow, setIsSlow] = useState(false);
  const scrollRef = useRef(null);
  const requestRef = useRef(0);

  useEffect(() => {
    scrollRef.current?.scrollTo({ top: scrollRef.current.scrollHeight, behavior: 'smooth' });
  }, [messages, isThinking, isSlow]);

  const send = async (text) => {
    const query = (typeof text === 'string' ? text : input).trim();
    if (!query || isThinking) return;

    const requestId = ++requestRef.current;
    setMessages((prev) => [...prev, { id: makeId(), role: 'user', text: query }]);
    setInput('');
    setIsThinking(true);
    setIsSlow(false);
    const slowTimer = setTimeout(() => setIsSlow(true), SLOW_REPLY_MS);

    let reply;
    try {
      const { answer, citation, coverage } = await sendChatQuery(query);
      reply = { role: 'assistant', text: answer, citation, coverage };
    } catch (err) {
      reply = { role: 'assistant', text: err.message, isError: true };
    } finally {
      clearTimeout(slowTimer);
    }

    // ignore replies to a conversation the user has since cleared
    if (requestId !== requestRef.current) return;
    setMessages((prev) => [...prev, { id: makeId(), ...reply }]);
    setIsThinking(false);
    setIsSlow(false);
  };

  const newChat = () => {
    requestRef.current++;
    setMessages([]);
    setInput('');
    setIsThinking(false);
    setIsSlow(false);
  };

  const isEmpty = messages.length === 0;

  return (
    <div className="relative flex h-[100dvh] flex-col">
      <AnimatedBackground />
      <ChatHeader onNewChat={newChat} showNewChat={!isEmpty} user={user} onLogout={onLogout} />

      <main ref={scrollRef} className="flex-1 overflow-y-auto">
        {isEmpty ? (
          <WelcomeScreen onPick={send} />
        ) : (
          <div className="mx-auto flex max-w-3xl flex-col gap-6 px-4 py-8 sm:px-6">
            <AnimatePresence initial={false}>
              {messages.map((m) => (
                <MessageBubble key={m.id} message={m} />
              ))}
            </AnimatePresence>
            {isThinking && <TypingIndicator slow={isSlow} />}
          </div>
        )}
      </main>

      <footer className="shrink-0 px-4 pb-4 pt-2 sm:px-6 sm:pb-6">
        <div className="mx-auto max-w-3xl">
          <ChatInput value={input} onChange={setInput} onSend={send} disabled={isThinking} />
          <p className="mt-2 text-center text-[11px] text-slate-500">
            Answers are generated by AI from placement records and may contain mistakes.
          </p>
        </div>
      </footer>
    </div>
  );
};

export default ChatPage;
